package io.github.task320.earthstep.feature.map

/**
 * 正距円筒図法のドット世界地図(P5-4)。
 *
 * 72x36 ドット(経度・緯度とも5度きざみ)の粗い陸地マスク。
 * `#` が陸、`.` が海。行0が北緯90度、行35が南緯90度、
 * 列0が西経180度、列71が東経175〜180度に対応する。
 *
 * **P6-3(ドット世界地図の制作)までの仮置き**。手書きの概形なので海岸線は正確ではない。
 * 差し替えるときは、この配列を同じ形式の素材で置き換える。
 *
 * 横方向はシームレスに繋がる(列71の右隣が列0)。周回のラップ処理はこれに依存している。
 */
object WorldMapDots {

    const val COLUMNS = 72
    const val ROWS = 36

    /** 赤道に対応する行。ここをトレイルが東へ進む(仕様5.1 の決定)。 */
    const val EQUATOR_ROW = 18

    val rows: List<String> = listOf(
        "........................................................................",
        "................#########.....###......#................................",
        "..............#############.######..........................#####.......",
        ".....##############################...#####..##########################.",
        "....###############################..###################################",
        "...###############################...###################################",
        "..###############################.######################################",
        "........#########################.######################################",
        "............#####################..#####################################",
        "............####################..#########.############################",
        "............###################...################################......",
        ".............##################....##############################.......",
        "..............################.....##############################.......",
        "...............#############......##############################........",
        ".................###########.....################.#############.........",
        "....................#########...#################...###########.........",
        "......................#########.#################....##########.........",
        "........................#######################..........########.......",
        "........................######################............#########.....",
        "........................#####################...............#########...",
        ".........................####################.............#########.....",
        ".........................#####################...........###########....",
        "..........................#################.##..........############....",
        "...........................################.............###########.....",
        "............................##############...............#########......",
        ".............................#######.........................#####...###",
        "..............................######.................................###",
        "...............................#####....................................",
        "................................####....................................",
        ".................................##.....................................",
        "........................................................................",
        "........................................................................",
        "........................................................................",
        "########################################################################",
        "########################################################################",
        "########################################################################",
    )

    /** [column], [row] が陸かどうか。列は左右に巻き取り、範囲外の行は海として扱う。 */
    fun isLand(column: Int, row: Int): Boolean {
        if (row !in rows.indices) return false
        val wrapped = ((column % COLUMNS) + COLUMNS) % COLUMNS
        return rows[row][wrapped] == '#'
    }
}
